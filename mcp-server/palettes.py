PALETTE_INFO = {name: f"{len(colors)} colors" for name, colors in PALETTES.items()}


def parse_color(color: str | list, palette_name: str | None = None) -> tuple[int, int, int]:
    if isinstance(color, (list, tuple)):
        return (int(color[0]), int(color[1]), int(color[2]))
    color = str(color).strip()
    if ":" in color:
        parts = color.split(":", 1)
        pal_name, idx = parts[0].strip(), parts[1].strip()
        if pal_name in PALETTES:
            return PALETTES[pal_name][int(idx) % len(PALETTES[pal_name])]
    try:
        rgb = ImageColor.getrgb(color)
        return (rgb[0], rgb[1], rgb[2])
    except (ValueError, AttributeError):
        return (0, 0, 0)


def nearest_palette_color(
    color: tuple[int, int, int],
    palette: list[tuple[int, int, int]],
) -> tuple[int, int, int]:
    return min(
        palette,
        key=lambda c: math.sqrt(
            (c[0] - color[0]) ** 2 + (c[1] - color[1]) ** 2 + (c[2] - color[2]) ** 2
        ),
    )
